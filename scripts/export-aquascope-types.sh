#!/usr/bin/env bash
# Regenerates src/analysis/bindings/ from the pinned Aquascope checkout (feature 003, R12).
#
#   scripts/export-aquascope-types.sh [path to Aquascope checkout]
#
# Runs Aquascope's own type export (its `export-ts` binary and its ts-rs export tests, as in
# its Makefile.toml `init-bindings` task) with the nightly from the checkout's
# rust-toolchain.toml, which needs rustc-dev. Rerun after every Aquascope upgrade.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
# shellcheck source=../spikes/002-toolchain-bundling/pin.env
source "$root/spikes/002-toolchain-bundling/pin.env"
src="${1:-$root/spikes/002-toolchain-bundling/work/src/aquascope}"
out="$root/src/analysis/bindings"

commit="$(git -C "$src" rev-parse HEAD)"
if [ "$commit" != "$AQUASCOPE_COMMIT" ]; then
  echo "checkout is at $commit but the pin is $AQUASCOPE_COMMIT ($AQUASCOPE_TAG)" >&2
  exit 1
fi

(cd "$src" && cargo run --locked --quiet --bin export-ts && cargo test --locked --quiet -p aquascope --lib export_bindings)

mkdir -p "$out"
rm -f "$out"/*.ts
cp "$src"/crates/aquascope/bindings/*.ts "$out/"
cat > "$out/README.md" <<EOF
# Aquascope result types

Generated by \`scripts/export-aquascope-types.sh\`; do not edit. Source: Aquascope $AQUASCOPE_TAG ($AQUASCOPE_COMMIT), $AQUASCOPE_REPO, exported with its ts-rs bindings. Aquascope is MIT licensed, copyright (c) 2022 Gavin Gray; see its LICENSE file.
EOF
ls "$out"
