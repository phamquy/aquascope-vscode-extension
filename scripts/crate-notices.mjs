#!/usr/bin/env node
// Prints the licence notices for the crates linked into the Aquascope binaries (feature 005, R7 and D4).
//
//   node scripts/crate-notices.mjs <Aquascope checkout> <rust toolchain> <host triple> > THIRD-PARTY-NOTICES
//
// Reads `cargo metadata` for the checkout's locked dependency graph on the host platform (crates for other
// platforms are never compiled into these binaries), walks it from `aquascope_front`
// (the package that builds `cargo-aquascope` and `aquascope-driver`), and copies each crate's licence
// files from its source in the cargo cache, which the build has just filled. Aquascope's own workspace
// crates are covered by its LICENSE, and the compiler crates it uses come from the toolchain, whose
// licence files the bundle keeps. Development-only dependencies are left out; build-time ones are kept,
// erring on the side of listing too much.
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';

const [checkout, toolchain, host] = process.argv.slice(2);
if (!checkout || !toolchain || !host) {
  console.error('usage: crate-notices.mjs <Aquascope checkout> <rust toolchain> <host triple>');
  process.exit(2);
}

const metadata = JSON.parse(
  execFileSync('cargo', [`+${toolchain}`, 'metadata', '--locked', '--format-version', '1', '--filter-platform', host, '--manifest-path', path.join(checkout, 'Cargo.toml')], {
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
  }),
);
const packages = new Map(metadata.packages.map((p) => [p.id, p]));
const nodes = new Map(metadata.resolve.nodes.map((n) => [n.id, n]));
const workspace = new Set(metadata.workspace_members);

const root = metadata.packages.find((p) => p.name === 'aquascope_front' && workspace.has(p.id));
if (!root) throw new Error('aquascope_front is not in the checkout');

// Every crate reachable from aquascope_front through normal or build dependencies.
const reached = new Set();
const stack = [root.id];
while (stack.length > 0) {
  const id = stack.pop();
  if (reached.has(id)) continue;
  reached.add(id);
  for (const dep of nodes.get(id)?.deps ?? []) {
    if (dep.dep_kinds.some((k) => k.kind !== 'dev')) stack.push(dep.pkg);
  }
}

const LICENCE_FILE = /^(licen[cs]e|copying|notice|copyright)/i;
const sections = [];
const withoutText = [];
const crates = [...reached].filter((id) => !workspace.has(id)).map((id) => packages.get(id));
crates.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
for (const crate of crates) {
  const dir = path.dirname(crate.manifest_path);
  const files = readdirSync(dir)
    .filter((f) => LICENCE_FILE.test(f) && statSync(path.join(dir, f)).isFile())
    .sort();
  const declared = crate.license ?? (crate.license_file ? `see ${crate.license_file}` : 'not declared');
  let body;
  if (files.length > 0) {
    body = files.map((f) => `--- ${f} ---\n${readFileSync(path.join(dir, f), 'utf8').trim()}`).join('\n\n');
  } else {
    withoutText.push(`${crate.name} ${crate.version}`);
    body = `The crate includes no licence file; its Cargo.toml declares the licence "${declared}".`;
  }
  const authors = crate.authors?.length ? `\nAuthors: ${crate.authors.join(', ')}` : '';
  sections.push(`${crate.name} ${crate.version} (licence: ${declared})${authors}\n\n${body}`);
}

const head =
  'Third-party notices for the Aquascope binaries\n\n' +
  'bin/cargo-aquascope and bin/aquascope-driver are built from Aquascope (see LICENSE) and statically ' +
  'link the following crates, listed with the versions in its Cargo.lock and the licence files they ' +
  'publish. Generated by scripts/crate-notices.mjs; do not edit.';
const sep = '\n\n' + '='.repeat(78) + '\n\n';
process.stdout.write(head + sep + sections.join(sep) + '\n');
console.error(`crate notices: ${crates.length} crates`);
if (withoutText.length > 0) console.error(`crate notices: no licence file in ${withoutText.join(', ')}`);
